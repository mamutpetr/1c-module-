@dataclass(frozen=True)
class Anode:
    key: str
    name: str
    composition_wt: dict          # масові частки, сума 1.0
    props: dict                   # ключ -> Prop
    note: str = ""
    warning: str = ""

    def electrons_per_gram(self) -> float:
        """моль e⁻ на грам сплаву за умови конгруентного розчинення всіх компонентів."""
        return sum(w * VALENCE[el] / MOLAR_MASS[el] for el, w in self.composition_wt.items())

    def specific_capacity_mah_g(self) -> float:
        return self.electrons_per_gram() * FARADAY / 3.6


